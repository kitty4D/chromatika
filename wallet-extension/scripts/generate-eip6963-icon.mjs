/**
 * rasterizes public/chromatika.svg to 96x96 (EIP-6963 / Wallet Standard data URI)
 * and writes:
 *   - public/chromatika-logo-eip6963-96.png
 *   - src/dapp-interface/eip6963-icon-data.ts
 *
 * run: pnpm run gen:eip6963-icon
 */
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const srcSvg = join(root, 'public/chromatika.svg');
const outPng = join(root, 'public/chromatika-logo-eip6963-96.png');
const outTs = join(root, 'src/dapp-interface/eip6963-icon-data.ts');

// high density so librsvg rasterizes at plenty of resolution before the 96x96 downscale
const buf = await sharp(srcSvg, { density: 300 })
  .resize(96, 96, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .png({ compressionLevel: 9 })
  .toBuffer();

writeFileSync(outPng, buf);
const b64 = buf.toString('base64');
writeFileSync(
  outTs,
  `/**\n * auto-generated by scripts/generate-eip6963-icon.mjs from public/chromatika.svg.\n * run \`pnpm run gen:eip6963-icon\` after changing the source logo.\n */\nexport const EIP6963_ICON_DATA_URI = 'data:image/png;base64,${b64}' as const;\n`,
);
console.log('wrote', outPng);
console.log('wrote', outTs, `(${buf.length} bytes png → ${b64.length} chars base64)`);
